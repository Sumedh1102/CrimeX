#!/usr/bin/env python
"""Assemble a self-contained FastAPI deployment directory for Vercel.

The API only reads pipeline outputs, so the bundle holds the Python packages it imports, the
config, the official statement, the processed data and the LATEST model and prediction
artifacts. Training-only dependencies (XGBoost, scikit-learn) stay out, which keeps the
function under Vercel's bundle-size limit.

Usage (after `make pipeline`):
    python scripts/build_vercel_api.py [--out .vercel-api]
    cd .vercel-api && npx vercel deploy --prod
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Runtime imports of backend.main (checked with sys.modules); no training libraries.
REQUIREMENTS = """\
fastapi>=0.115
numpy>=2.0
pandas>=2.2
pyarrow>=15
scipy>=1.12
pydantic>=2.7
pyyaml>=6
global-land-mask>=1.0
"""

# Vercel's FastAPI preset picks up `app` from app.py at the project root.
ENTRYPOINT = '''\
"""Vercel entry point for the CrimeX API (generated by scripts/build_vercel_api.py)."""

from backend.main import app

__all__ = ["app"]
'''

IGNORE = shutil.ignore_patterns("__pycache__", "*.py[cod]", "tests")


def _copy_latest(src_dir: Path, dst_dir: Path) -> str:
    pointer = src_dir / "LATEST"
    if not pointer.exists():
        raise SystemExit(f"Missing {pointer}. Run `make pipeline` first.")
    version = pointer.read_text(encoding="utf-8").strip()
    shutil.copytree(src_dir / version, dst_dir / version)
    shutil.copy2(pointer, dst_dir / "LATEST")
    return version


def build(out: Path) -> None:
    processed = ROOT / "data" / "processed"
    if not (processed / "incidents.parquet").exists():
        raise SystemExit(f"Missing {processed}. Run `make pipeline` first.")

    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    for pkg in ("backend", "ml", "configs"):
        shutil.copytree(ROOT / pkg, out / pkg, ignore=IGNORE)
    shutil.copytree(processed, out / "data" / "processed")
    official = out / "data" / "official"
    official.mkdir(parents=True)
    for path in (ROOT / "data" / "official").glob("*.json"):
        shutil.copy2(path, official / path.name)

    model = _copy_latest(ROOT / "artifacts" / "models", out / "artifacts" / "models")
    preds = _copy_latest(ROOT / "artifacts" / "predictions", out / "artifacts" / "predictions")

    (out / "requirements.txt").write_text(REQUIREMENTS, encoding="utf-8")
    (out / "app.py").write_text(ENTRYPOINT, encoding="utf-8")
    (out / ".python-version").write_text("3.12\n", encoding="utf-8")

    size_mb = sum(p.stat().st_size for p in out.rglob("*") if p.is_file()) / 1e6
    print(f"wrote {out} ({size_mb:.1f} MB): model {model}, predictions {preds}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=ROOT / ".vercel-api")
    args = parser.parse_args()
    build(args.out.resolve())
    return 0


if __name__ == "__main__":
    sys.exit(main())
